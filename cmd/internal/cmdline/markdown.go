package cmdline

import (
	"fmt"
	"io"
	"strings"
)

// WriteMarkdown is the whole reference: every command that is not hidden, with its subcommands, in the order help lists them.
func (p *Program) WriteMarkdown(w io.Writer) {
	fmt.Fprintf(w, "# %s command reference\n\n", p.Name)
	fmt.Fprintf(w, "This file is generated by `%s help --markdown`. Edit the command table in the source, not this file.\n\n", p.Name)
	fmt.Fprintf(w, "%s\n\n", p.Tagline)
	fmt.Fprintf(w, "## Commands\n\n")
	for _, group := range p.Groups {
		fmt.Fprintf(w, "**%s**\n\n", group)
		for _, command := range visible(p.Commands) {
			if command.Group == group {
				fmt.Fprintf(w, "- [`%s %s`](#%s): %s\n", p.Name, command.Name, anchor(p.Name+" "+command.Name), command.Summary)
			}
		}
		fmt.Fprintln(w)
	}
	fmt.Fprintf(w, "## Exit codes\n\n")
	writeMarkdownParams(w, p.Exit)
	for _, group := range p.Groups {
		for _, command := range visible(p.Commands) {
			if command.Group == group {
				p.writeMarkdownCommand(w, []*Command{command}, 1)
			}
		}
	}
}

func (p *Program) writeMarkdownCommand(w io.Writer, chain []*Command, level int) {
	d := p.describe(chain)
	fmt.Fprintf(w, "\n%s `%s`\n\n%s\n\n```text\n", strings.Repeat("#", level+1), d.Path, d.Summary)
	fmt.Fprintln(w, strings.Join(d.Usage, "\n")+"\n```")
	if d.Description != "" {
		fmt.Fprintf(w, "\n%s\n", d.Description)
	}
	markdownSection(w, "Arguments", d.Args)
	markdownSection(w, "Commands", d.Subs)
	markdownSection(w, "Flags", d.Flags)
	markdownSection(w, "Environment", d.Env)
	markdownSection(w, "Exit codes", chain[len(chain)-1].Exit)
	if len(d.Examples) > 0 {
		fmt.Fprintf(w, "\nExamples:\n\n```sh\n%s\n```\n", strings.Join(d.Examples, "\n"))
	}
	if len(d.SeeAlso) > 0 {
		fmt.Fprintf(w, "\nSee also: `%s`\n", strings.Join(d.SeeAlso, "`, `"))
	}
	for _, sub := range visible(chain[len(chain)-1].Subs) {
		p.writeMarkdownCommand(w, append(append([]*Command{}, chain...), sub), level+1)
	}
}

func markdownSection(w io.Writer, title string, params []Param) {
	if len(params) == 0 {
		return
	}
	fmt.Fprintf(w, "\n%s:\n\n", title)
	writeMarkdownParams(w, params)
}

func writeMarkdownParams(w io.Writer, params []Param) {
	for _, param := range params {
		fmt.Fprintf(w, "- `%s`: %s\n", param.Name, param.Text)
	}
}

func anchor(heading string) string {
	return strings.ReplaceAll(strings.ToLower(heading), " ", "-")
}
